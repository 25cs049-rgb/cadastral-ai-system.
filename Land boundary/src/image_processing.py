"""
AI-Assisted Land Boundary Verification & Cadastral Intelligence System
Image Processing & Computer Vision Module (OpenCV & PIL)

Handles cadastral map loading (PNG, JPG, JPEG, TIFF), multi-stage preprocessing,
and candidate land boundary contour extraction with polygon approximation.

DISCLAIMER: Algorithmic candidate boundaries generated by computer vision
are advisory aids for surveyor verification and do not constitute legally verified boundaries.
"""

import cv2
import numpy as np
from PIL import Image
import io
import math
from typing import Tuple, List, Dict, Any, Optional


def load_image(file_bytes: bytes, filename: str) -> np.ndarray:
    """
    Load cadastral map from bytes into OpenCV BGR numpy array.
    Supports PNG, JPG, JPEG, and TIFF (including multi-page or 16-bit).
    """
    ext = filename.lower().split('.')[-1]
    
    # Try decoding directly with OpenCV
    np_arr = np.frombuffer(file_bytes, np.uint8)
    image = cv2.imdecode(np_arr, cv2.IMREAD_COLOR)

    # Fallback to PIL if OpenCV fails (common for certain TIFF compressions)
    if image is None:
        try:
            pil_img = Image.open(io.BytesIO(file_bytes))
            # If multi-page TIFF, read first page
            pil_img.seek(0)
            if pil_img.mode != "RGB":
                pil_img = pil_img.convert("RGB")
            rgb_arr = np.array(pil_img)
            image = cv2.cvtColor(rgb_arr, cv2.COLOR_RGB2BGR)
        except Exception as e:
            raise ValueError(f"Failed to decode image '{filename}': {str(e)}")

    if image is None:
        raise ValueError(f"Could not load image '{filename}'. Format might be unsupported or corrupt.")

    return image


def preprocess_cadastral_map(
    image: np.ndarray,
    method: str = "adaptive",
    blur_kernel_size: int = 3,
    adaptive_block_size: int = 15,
    adaptive_c: int = 4,
    canny_thresh1: int = 50,
    canny_thresh2: int = 150,
    apply_clahe: bool = True,
    morph_close_kernel: int = 2
) -> Dict[str, np.ndarray]:
    """
    Multi-stage cadastral map preprocessing pipeline.
    
    Returns a dictionary of stages:
    - 'gray': Grayscale representation
    - 'enhanced': CLAHE contrast-enhanced grayscale
    - 'denoised': Bilaterally filtered or blurred image
    - 'binary': High-contrast inverted binary mask (boundaries as white lines)
    - 'edges': Canny edge detection map
    - 'morph': Morphologically closed binary map to seal dashed cadastral lines
    """
    # 1. Grayscale
    if len(image.shape) == 3:
        gray = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY)
    else:
        gray = image.copy()

    # 2. Contrast Enhancement (CLAHE - excellent for faint cadastral ink/lines)
    if apply_clahe:
        clahe = cv2.createCLAHE(clipLimit=2.0, tileGridSize=(8, 8))
        enhanced = clahe.apply(gray)
    else:
        enhanced = gray.copy()

    # 3. Denoising / Smoothing
    k = max(3, blur_kernel_size if blur_kernel_size % 2 == 1 else blur_kernel_size + 1)
    denoised = cv2.bilateralFilter(enhanced, d=5, sigmaColor=50, sigmaSpace=50)

    # 4. Binarization / Thresholding
    if method == "adaptive":
        blk = max(3, adaptive_block_size if adaptive_block_size % 2 == 1 else adaptive_block_size + 1)
        # Using THRESH_BINARY_INV so cadastral ink boundaries become foreground (255)
        binary = cv2.adaptiveThreshold(
            denoised, 255, cv2.ADAPTIVE_THRESH_GAUSSIAN_C,
            cv2.THRESH_BINARY_INV, blk, adaptive_c
        )
    elif method == "otsu":
        _, binary = cv2.threshold(denoised, 0, 255, cv2.THRESH_BINARY_INV + cv2.THRESH_OTSU)
    else:  # Simple Canny-based
        edges = cv2.Canny(denoised, canny_thresh1, canny_thresh2)
        binary = edges

    # 5. Canny edges
    edges = cv2.Canny(denoised, canny_thresh1, canny_thresh2)

    # 6. Morphological operations: Close gaps in broken/dashed cadastral boundaries
    morph = binary.copy()
    if morph_close_kernel > 0:
        kernel = cv2.getStructuringElement(cv2.MORPH_RECT, (morph_close_kernel, morph_close_kernel))
        morph = cv2.morphologyEx(binary, cv2.MORPH_CLOSE, kernel, iterations=1)

    return {
        "gray": gray,
        "enhanced": enhanced,
        "denoised": denoised,
        "binary": binary,
        "edges": edges,
        "morph": morph
    }


def detect_candidate_boundaries(
    binary_map: np.ndarray,
    min_area_ratio: float = 0.0005,
    max_area_ratio: float = 0.85,
    epsilon_factor: float = 0.012
) -> List[Dict[str, Any]]:
    """
    Detect candidate cadastral land parcels from binary boundary mask.
    
    Uses contour topology analysis, Ramer-Douglas-Peucker polygon approximation,
    and geometric property calculation (area, perimeter, compactness index).
    
    Parameters:
    - binary_map: Single-channel uint8 binary image (255 = boundary edges)
    - min_area_ratio: Minimum parcel area relative to total map area (filters noise/text)
    - max_area_ratio: Maximum parcel area relative to total map area (filters outer frame)
    - epsilon_factor: Douglas-Peucker approximation accuracy ratio
    """
    height, width = binary_map.shape[:2]
    total_image_area = width * height
    min_area = total_image_area * min_area_ratio
    max_area = total_image_area * max_area_ratio

    # Find contours with hierarchy
    contours, hierarchy = cv2.findContours(
        binary_map, cv2.RETR_CCOMP, cv2.CHAIN_APPROX_SIMPLE
    )

    detected_parcels = []
    idx = 1

    for c in contours:
        raw_area = cv2.contourArea(c)
        if raw_area < min_area or raw_area > max_area:
            continue

        perimeter = cv2.arcLength(c, closed=True)
        if perimeter == 0:
            continue

        # Polygon approximation using Douglas-Peucker
        epsilon = epsilon_factor * perimeter
        approx = cv2.approxPolyDP(c, epsilon, closed=True)

        if len(approx) < 3:
            continue

        approx_area = cv2.contourArea(approx)
        if approx_area < min_area:
            continue

        # Centroid calculation via moments
        m = cv2.moments(approx)
        if m["m00"] != 0:
            cx = float(m["m10"] / m["m00"])
            cy = float(m["m01"] / m["m00"])
        else:
            pts = approx.reshape(-1, 2)
            cx = float(np.mean(pts[:, 0]))
            cy = float(np.mean(pts[:, 1]))

        # Polsby-Popper Compactness metric: (4 * pi * Area) / (Perimeter^2)
        # Circle = 1.0, Square ~ 0.785, Thin sliver/noise < 0.15
        compactness = (4.0 * math.pi * approx_area) / (perimeter ** 2) if perimeter > 0 else 0.0

        # Bounding box
        x, y, w, h = cv2.boundingRect(approx)

        # Coordinate list [[x1, y1], [x2, y2], ...]
        coords = approx.reshape(-1, 2).tolist()

        detected_parcels.append({
            "parcel_index": idx,
            "survey_number": f"CAD-{idx:03d}",
            "polygon_coords": coords,
            "raw_contour": c,
            "approx_contour": approx,
            "area_pixels": round(approx_area, 2),
            "perimeter_pixels": round(perimeter, 2),
            "compactness": round(compactness, 4),
            "centroid_x": round(cx, 1),
            "centroid_y": round(cy, 1),
            "bbox": (x, y, w, h),
            "verification_status": "Pending Review",
            "discrepancy_flags": [],
            "surveyor_notes": ""
        })
        idx += 1

    # Sort parcels geometrically (top-to-bottom, left-to-right) for logical indexing
    detected_parcels.sort(key=lambda p: (p["centroid_y"] // 100, p["centroid_x"]))
    for i, p in enumerate(detected_parcels, start=1):
        p["parcel_index"] = i
        p["survey_number"] = f"CAD-{i:03d}"

    return detected_parcels


def render_boundary_overlay(
    image: np.ndarray,
    parcels: List[Dict[str, Any]],
    show_labels: bool = True,
    show_centroids: bool = True,
    highlight_flagged: bool = True,
    alpha_fill: float = 0.25,
    theme: str = "railmark"
) -> np.ndarray:
    """
    Render candidate parcel boundary polygons on top of the map image.
    Supports 'railmark' dark high-tech styling (electric cyan, neon royal blue, emerald, crimson)
    and standard light theme.
    """
    overlay = image.copy()
    fill_layer = image.copy()

    # Pre-draw polygon fills
    for p in parcels:
        coords = p.get("polygon_coords", [])
        if len(coords) < 3:
            continue

        pts = np.array(coords, dtype=np.int32).reshape((-1, 1, 2))
        flags = p.get("discrepancy_flags", [])
        status = p.get("verification_status", "Pending Review")

        # Color selection based on status / discrepancy (BGR format for OpenCV)
        if flags and highlight_flagged:
            fill_color = (40, 40, 230)      # Vivid Crimson (BGR)
        elif status == "Approved":
            fill_color = (60, 200, 80)      # Emerald Green
        elif status == "Corrected":
            fill_color = (20, 180, 245)     # Amber / Gold
        elif status == "Rejected":
            fill_color = (90, 90, 100)      # Slate Gray
        else:
            # Candidate pending - Electric Cyan (#00B8E6 -> BGR: 230, 184, 0)
            fill_color = (230, 184, 0) if theme == "railmark" else (235, 140, 37)

        # Draw translucent filled polygon
        cv2.fillPoly(fill_layer, [pts], fill_color)

    # Blend fill layer with original
    cv2.addWeighted(fill_layer, alpha_fill, overlay, 1.0 - alpha_fill, 0, overlay)

    # Draw sharp boundary outlines and text labels
    for p in parcels:
        coords = p.get("polygon_coords", [])
        if len(coords) < 3:
            continue

        pts = np.array(coords, dtype=np.int32).reshape((-1, 1, 2))
        flags = p.get("discrepancy_flags", [])
        status = p.get("verification_status", "Pending Review")

        if flags and highlight_flagged:
            line_color = (30, 30, 240)      # Neon Crimson Outline
            thickness = 3
        elif status == "Approved":
            line_color = (40, 210, 80)      # Bright Emerald
            thickness = 2
        elif status == "Corrected":
            line_color = (0, 160, 240)      # Bright Gold/Amber
            thickness = 2
        elif status == "Rejected":
            line_color = (80, 80, 90)       # Muted Gray
            thickness = 2
        else:
            # Electric Royal Blue / Cyan
            line_color = (240, 160, 0) if theme == "railmark" else (180, 90, 15)
            thickness = 2

        cv2.polylines(overlay, [pts], isClosed=True, color=line_color, thickness=thickness)

        cx, cy = int(p.get("centroid_x", 0)), int(p.get("centroid_y", 0))

        if show_centroids:
            # Glowing double-circle centroid
            centroid_color = (240, 200, 0) if theme == "railmark" else (0, 0, 180)
            cv2.circle(overlay, (cx, cy), 5, centroid_color, -1)
            cv2.circle(overlay, (cx, cy), 7, (255, 255, 255), 1)

        if show_labels:
            label = str(p.get("survey_number", f"P{p.get('parcel_index', '')}"))
            font = cv2.FONT_HERSHEY_SIMPLEX
            scale = 0.45
            thick = 1
            (tw, th), baseline = cv2.getTextSize(label, font, scale, thick)

            # High-tech badge badge behind label
            pad = 4
            bx1 = max(0, cx - tw // 2 - pad)
            by1 = max(0, cy - th // 2 - pad)
            bx2 = min(overlay.shape[1], cx + tw // 2 + pad)
            by2 = min(overlay.shape[0], cy + th // 2 + pad)

            if theme == "railmark":
                # Dark obsidian navy badge (#0D1B30) with glowing colored border
                badge_bg = (48, 27, 13)       # BGR for #0D1B30
                text_color = (255, 255, 255)
                if flags and highlight_flagged:
                    border_color = (30, 30, 240)
                    text_color = (180, 180, 255)
                elif status == "Approved":
                    border_color = (40, 210, 80)
                else:
                    border_color = (230, 184, 0) # Cyan border
            else:
                badge_bg = (255, 255, 255)
                border_color = line_color
                text_color = (20, 20, 20)

            cv2.rectangle(overlay, (bx1, by1), (bx2, by2), badge_bg, -1)
            cv2.rectangle(overlay, (bx1, by1), (bx2, by2), border_color, 1)
            cv2.putText(overlay, label, (bx1 + pad, by2 - pad), font, scale, text_color, thick, cv2.LINE_AA)

    return overlay


def generate_synthetic_cadastral_map(width: int = 1000, height: int = 800) -> np.ndarray:
    """
    Generate a realistic synthetic cadastral survey map for demonstration and testing.
    Includes parcel boundary grid with irregular lots, stamped survey numbers, and road reserve.
    """
    # Parchment-like aged cadastral map background
    canvas = np.full((height, width, 3), 250, dtype=np.uint8)

    # Add subtle paper texture noise
    noise = np.random.randint(-5, 5, (height, width, 3), dtype=np.int16)
    canvas = np.clip(canvas.astype(np.int16) + noise, 0, 255).astype(np.uint8)

    # Map outer margin / boundary frame
    margin = 50
    cv2.rectangle(canvas, (margin, margin), (width - margin, height - margin), (20, 20, 20), 3)
    cv2.rectangle(canvas, (margin + 6, margin + 6), (width - margin - 6, height - margin - 6), (60, 60, 60), 1)

    # Road reserve running diagonally
    road_pts = np.array([
        [margin, 420], [width - margin, 460],
        [width - margin, 520], [margin, 480]
    ], dtype=np.int32)
    cv2.polylines(canvas, [road_pts], True, (30, 30, 30), 2)
    cv2.putText(canvas, "VILLAGE MAIN ROAD (20m WIDE)", (320, 495), cv2.FONT_HERSHEY_SIMPLEX, 0.5, (50, 50, 50), 1, cv2.LINE_AA)

    # Parcel definitions: list of (polygon_vertices, survey_number_label)
    parcels_def = [
        # Northern row
        ([[margin, margin], [320, margin], [340, 240], [margin, 220]], "101"),
        ([[320, margin], [580, margin], [600, 250], [340, 240]], "102/1"),
        ([[580, margin], [width - margin, margin], [width - margin, 260], [600, 250]], "102/2"),

        # Middle row (North of road)
        ([[margin, 220], [340, 240], [330, 425], [margin, 420]], "103"),
        ([[340, 240], [600, 250], [590, 440], [330, 425]], "104-A"),
        ([[600, 250], [width - margin, 260], [width - margin, 460], [590, 440]], "104-B"),

        # Southern row (South of road)
        ([[margin, 480], [280, 490], [260, height - margin], [margin, height - margin]], "105"),
        ([[280, 490], [520, 500], [500, height - margin], [260, height - margin]], "106/A"),
        ([[520, 500], [750, 510], [730, height - margin], [500, height - margin]], "106/B"),
        ([[750, 510], [width - margin, 520], [width - margin, height - margin], [730, height - margin]], "107"),
    ]

    # Draw parcels
    for pts, s_no in parcels_def:
        poly = np.array(pts, dtype=np.int32).reshape((-1, 1, 2))
        cv2.polylines(canvas, [poly], isClosed=True, color=(20, 20, 20), thickness=2)

        # Centroid for text
        m = cv2.moments(poly)
        if m["m00"] != 0:
            cx = int(m["m10"] / m["m00"])
            cy = int(m["m01"] / m["m00"])
        else:
            cx = int(np.mean([p[0] for p in pts]))
            cy = int(np.mean([p[1] for p in pts]))

        # Render printed survey number text
        cv2.putText(canvas, s_no, (cx - 24, cy + 8), cv2.FONT_HERSHEY_SIMPLEX, 0.75, (20, 20, 20), 2, cv2.LINE_AA)

    # Cadastral title block
    cv2.putText(canvas, "CADASTRAL SURVEY SHEET - VILLAGE BLOCK 14", (margin + 20, margin + 30),
                cv2.FONT_HERSHEY_SIMPLEX, 0.6, (10, 10, 10), 2, cv2.LINE_AA)
    cv2.putText(canvas, "SCALE: 1:1000 | REVENUE SURVEY DEPARTMENT", (margin + 20, margin + 50),
                cv2.FONT_HERSHEY_SIMPLEX, 0.45, (80, 80, 80), 1, cv2.LINE_AA)

    # North indicator
    nx, ny = width - margin - 50, margin + 60
    cv2.arrowedLine(canvas, (nx, ny + 30), (nx, ny - 20), (20, 20, 20), 2, tipLength=0.3)
    cv2.putText(canvas, "N", (nx - 6, ny - 25), cv2.FONT_HERSHEY_SIMPLEX, 0.6, (20, 20, 20), 2, cv2.LINE_AA)

    return canvas

